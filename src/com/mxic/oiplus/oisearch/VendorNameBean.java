package com.mxic.oiplus.oisearch;

public class VendorNameBean {
  public VendorNameBean() {
  }

  private String sid;
  private String product_body;
  private String brand;
  private String version;
  private String vendor;

  public void setSid(String sid) {
    this.sid = sid;
  }

  public String getSid() {
    return sid;
  }

  public void setProduct_body(String product_body) {
    this.product_body = product_body;
  }

  public String getProduct_body() {
    return product_body;
  }

  public void setBrand(String brand) {
    this.brand = brand;
  }

  public String getBrand() {
    return brand;
  }

  public void setVersion(String version) {
    this.version = version;
  }

  public String getVersion() {
    return version;
  }

  public void setVendor(String vendor) {
    this.vendor = vendor;
  }

  public String getVendor() {
    return vendor;
  }
}
