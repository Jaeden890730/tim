package com.mxic.oiplus.oimaintain;

public class YieldBin {
  private String bin_no;
  private String short_name;
  private String if_bin_no;
  private String snova_id;
  private String version;

  public String getBin_no() {
	  return bin_no;
  }

  public void setBin_no(String bin_no) {
	  this.bin_no = bin_no;
  }

  
public String getShort_name() {
	  return short_name;
  }

  public void setShort_name(String short_name) {
	  this.short_name = short_name;
  }

    public String getIf_bin_no() {
        return if_bin_no;
    }
    
    public void setIf_bin_no(String if_bin_no) {
        this.if_bin_no = if_bin_no;
    }
    
    public String getSnova_id() {
        return snova_id;
    }
    
    public void setSnova_id(String snova_id) {
        this.snova_id = snova_id;
    }
    
    public String getVersion() {
    	return version;
    }

    public void setVersion(String version) {
    	this.version = version;
    }

}
